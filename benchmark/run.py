"""Run the benchmark ablations and emit a results table.

Ablations isolate the two contributions:

* **full**        — context (code/doc) + lineage-aware wave scheduling (the method).
* **no-lineage**  — same context, but upstream descriptions are not inherited
                    (every table generated in isolation).
* **no-context**  — lineage kept, but no code/doc context is provided.
* **schema-only** — neither context nor lineage (names + types only): the baseline.

By default it uses the deterministic :class:`MockBackend` so results are reproducible
without API keys. Pass ``--provider openai|anthropic|bedrock|vertex|azure`` (and set
the provider's credentials) to reproduce with a real cloud model.

Usage:
    python -m benchmark.run                       # reproducible mock run
    python -m benchmark.run --provider anthropic --model claude-3-5-sonnet-latest
"""
from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path

from openmetadatagenerator.config import GenerationConfig
from openmetadatagenerator.context.embedding import EmbeddingIndex
from openmetadatagenerator.generation import Generator
from .evaluate import evaluate
from .generate import build_benchmark


def _make_llm(provider: str, model: str):
    if provider == "mock":
        from .mock_llm import MockBackend
        return MockBackend()
    from openmetadatagenerator.llm import get_backend
    return get_backend(provider, model)


def _n_objects(tables) -> int:
    return len(tables) + sum(len(t.columns) for t in tables)


def _make_instance(benchmark: str, ctx: bool, n_entities: int, seed: int):
    """Build a (tables, gold) instance for the requested benchmark + context setting."""
    if benchmark == "tpch":
        from .public_tpch import build_tpch
        return build_tpch(with_doc_context=ctx)
    if benchmark == "sakila":
        from .public_sakila import build_sakila
        return build_sakila(with_doc_context=ctx)
    return build_benchmark(n_entities=n_entities, seed=seed,
                           context_prob=0.8 if ctx else 0.0)


def run(provider: str = "mock", model: str = "", n_entities: int = 5,
        seed: int = 7, benchmark: str = "synthetic") -> dict:
    index = EmbeddingIndex()
    cfg = GenerationConfig(workers=4)
    results_by_ablation: dict[str, dict] = {}

    ablations = {
        "full":        dict(ctx=True,  lineage=True),
        "no-lineage":  dict(ctx=True,  lineage=False),
        "no-context":  dict(ctx=False, lineage=True),
        "schema-only": dict(ctx=False, lineage=False),
    }

    print(f"# benchmark={benchmark}  provider={provider}  model={model or '(default)'}")
    for name, opt in ablations.items():
        tables, gold = _make_instance(benchmark, opt["ctx"], n_entities, seed)
        tables = copy.deepcopy(tables)
        if not opt["lineage"]:
            for t in tables:               # sever lineage: no wave inheritance
                t.upstreams = []
                for c in t.columns:
                    c.upstreams = []
        n_expected = _n_objects(tables)
        llm = _make_llm(provider, model)
        gen = Generator(llm, index, cfg)
        res = gen.run(tables)
        m = evaluate(res, gold, n_expected, index)
        results_by_ablation[name] = m.__dict__
        print(f"{name:12s} | {m.row()}")

    out = {"provider": provider, "model": model or "(default)", "benchmark": benchmark,
           "n_entities": n_entities, "seed": seed, "ablations": results_by_ablation}
    Path("benchmark").mkdir(exist_ok=True)
    suffix = "" if benchmark == "synthetic" else f"_{benchmark}"
    Path(f"benchmark/results{suffix}.json").write_text(json.dumps(out, indent=2))
    _write_latex(results_by_ablation, f"paper/results_table{suffix}.tex")
    return out


def _write_latex(res: dict, path: str = "paper/results_table.tex") -> None:
    rows = []
    label = {"full": "Full (context + lineage)", "no-lineage": "-- lineage inheritance",
             "no-context": "-- code/doc context", "schema-only": "Schema-only (baseline)"}
    for k in ("schema-only", "no-context", "no-lineage", "full"):
        m = res[k]
        rows.append(f"{label[k]} & {m['coverage']:.2f} & {m['accuracy']:.3f} & "
                    f"{m['faithfulness']:.3f} & {m['exact_grain']:.2f} \\\\")
    body = "\n".join(rows)
    tex = (
        "% auto-generated by benchmark/run.py\n"
        "\\begin{tabular}{lcccc}\n\\toprule\n"
        "Configuration & Coverage & Accuracy & Faithfulness & Grain \\\\\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n")
    Path(path).write_text(tex)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--provider", default="mock")
    ap.add_argument("--model", default="")
    ap.add_argument("--benchmark", choices=["synthetic", "tpch", "sakila"], default="synthetic")
    ap.add_argument("--n-entities", type=int, default=5)
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()
    run(args.provider, args.model, args.n_entities, args.seed, args.benchmark)
